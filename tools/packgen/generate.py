        # Provider and model are deliberately empty: choose current IDs after spike S3 (docs/verification-log.md).
        routes += [f";default;PROVIDER_ROUTE;;route.{task}.provider;;true;0", f";default;PROVIDER_ROUTE;;route.{task}.model;;true;0",
                   f";default;PROVIDER_ROUTE;;route.{task}.fallback;;true;0"]
