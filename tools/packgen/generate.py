    toggles = [f";default;TOGGLE;;capability.{c}.enabled;true;true;0" for c in caps]
    defaults = {
        "orchestration.maxSteps": "8", "orchestration.maxSeconds": "9", "clarification.maxQuestions": "2", "context.maxTurns": "6",
        "context.maxChars": "2000", "replenishment.windowDays": "180", "replenishment.minOrders": "3", "replenishment.dueRatio": "0.9",
        "patternChange.thresholdPct": "30", "patternChange.minSample": "2", "patternChange.recentOrders": "2", "budget.candidateCap": "30",
        "crossSell.minSupport": "2", "bundle.minSupport": "3", "decision.minConfidencePercent": "40",
        "privacy.interestEvents.enabled": "true", "privacy.interestEvents.retentionDays": "90", "privacy.feedback.retentionDays": "180",
        "privacy.interestEvents.noticeText": "PLACEHOLDER (owner and legal to confirm): this assistant records which products you view, compare or ask about to improve suggestions. You can switch this off.",
        "contact.text": "Please contact your account manager.", "usage.cap.messages": "200", "usage.cap.tokens": "200000", "usage.cap.period": "DAY",
        "stock.demoNotice": "Demo stock", "purchaseList.label": "Demo purchase list, not your cart"}
    routes = []
