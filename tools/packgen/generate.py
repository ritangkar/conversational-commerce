#!/usr/bin/env python3
"""Deterministic pack generator (D32). Reads manifests/*.json, validates them against schema/pack.schema.json (subset validator,
no third-party packages), and writes ImpEx plus order plans under backend/ccsampledata/resources/ccsampledata/import/.
Same input always gives byte-identical output; CI regenerates and runs `git diff --exit-code`.
ASSUMPTION AS-10: ImpEx syntax follows platform conventions from memory (E17 secondary); it has not been loaded into a platform.
Manifests are JSON, not YAML, to avoid a dependency (docs/assumptions.md AS-11)."""
import json, pathlib, random, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = ROOT / "tools/packgen"
OUT = ROOT / "backend/ccsampledata/resources/ccsampledata/import"
CAPS_JAVA = ROOT / "backend/cccore/src/com/conversational/commerce/core/engine/model/Capabilities.java"
TYPES = {"string": str, "array": list, "object": dict, "integer": int, "boolean": bool}


def validate(value, schema, path="$"):
    errors = []
    t = schema.get("type")
    if t and not isinstance(value, TYPES[t]):
        return [f"{path}: expected {t}"]
    if isinstance(value, dict):
        for r in schema.get("required", []):
            if r not in value:
                errors.append(f"{path}: missing '{r}'")
        for k, sub in schema.get("properties", {}).items():
            if k in value:
                errors += validate(value[k], sub, f"{path}.{k}")
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            errors.append(f"{path}: too few items")
        for i, item in enumerate(value):
            if "items" in schema:
                errors += validate(item, schema["items"], f"{path}[{i}]")
    if isinstance(value, str) and "pattern" in schema and not re.search(schema["pattern"], value):
        errors.append(f"{path}: does not match {schema['pattern']}")
    return errors


def esc(v):
    return str(v).replace(";", ",").replace("\n", " ")


def products_of(m):
    prods = [dict(p) for p in m["products"]]
    s = m["synthetic"]
    rng = random.Random(s["seed"])
    prefix = m["codePattern"].split("#")[0]
    t = s["template"]
    for i in range(s["extraProducts"]):
        lo, hi = t["priceMinor"]
        prods.append({"code": f"{prefix}{9000 + i}", "name": f"{t['namePrefix']} {i + 1:02d}", "description": f"Synthetic demo item {i + 1}",
                      "priceMinor": rng.randrange(lo // 100, hi // 100) * 100, "attributes": {}, "category": t["category"]})
    return prods


def impex_pack(m):
    p = m["pack"]
    cv = "ccProductCatalog:Online"
    L = [f"# GENERATED by tools/packgen/generate.py from manifests/{p}.json. Do not edit. Synthetic data only.",
         "$catalogVersion=catalogVersion(catalog(id),version)[unique=true,default=ccProductCatalog:Online]",
         f"$supercategories=supercategories(code,{'catalogVersion(catalog(id),version)'})",
         "", "INSERT_UPDATE Catalog;id[unique=true];name[lang=en]", ";ccProductCatalog;CC demo product catalog",
         "INSERT_UPDATE CatalogVersion;catalog(id)[unique=true];version[unique=true];active", ";ccProductCatalog;Online;true",
         "", "INSERT_UPDATE Category;code[unique=true];name[lang=en];$catalogVersion;supercategories(code,catalogVersion(catalog(id),version))",
         f";{m['rootCategory']};{esc(m['displayName'])};;"]
    for c in m["categories"]:
        L.append(f";{c['code']};{esc(c['name'])};;{m['rootCategory']}:{cv}")
    prods = products_of(m)
    L += ["", "INSERT_UPDATE Product;code[unique=true];name[lang=en];description[lang=en];unit(code)[default=pieces];$catalogVersion;"
          "approvalStatus(code);supercategories(code,catalogVersion(catalog(id),version))"]
    for q in prods:
        L.append(f";{q['code']};{esc(q['name'])};{esc(q['description'])};;;{'unapproved' if q.get('discontinued') else 'approved'};"
                 f"{q.get('category', m['categories'][0]['code'])}:{cv}")
    discontinued = [q for q in prods if q.get("replacement")]
    if discontinued:
        L += ["", "INSERT_UPDATE ProductReference;source(code,catalogVersion(catalog(id),version))[unique=true];target(code,catalogVersion(catalog(id),version))[unique=true];referenceType(code)[unique=true];active"]
        for q in discontinued:
            L.append(f";{q['code']}:{cv};{q['replacement']}:{cv};FOLLOWUP;true")
    L += ["", "INSERT_UPDATE PriceRow;product(code,catalogVersion(catalog(id),version))[unique=true];price[unique=true];currency(isocode)[unique=true];unit(code)[default=pieces];net[default=true]"]
    for q in prods:
        L.append(f";{q['code']}:{cv};{q['priceMinor'] / 100:.2f};INR;;")
    # classification attributes so comparison and filters work (PD-02, PD-04, PD-05)
    attrs = sorted({a for q in prods for a in q["attributes"]})
    if attrs:
        cls = f"cc{p}"
        L += ["", "INSERT_UPDATE ClassificationSystem;id[unique=true]", ";ccClassification",
              "INSERT_UPDATE ClassificationSystemVersion;catalog(id)[unique=true];version[unique=true];active", ";ccClassification;1.0;true",
              "INSERT_UPDATE ClassificationClass;code[unique=true];catalogVersion(catalog(id),version)[unique=true];name[lang=en]", f";{cls};ccClassification:1.0;{esc(m['displayName'])}",
              "INSERT_UPDATE ClassificationAttribute;code[unique=true];systemVersion(catalog(id),version)[unique=true]"]
        L += [f";{a};ccClassification:1.0" for a in attrs]
        L += ["INSERT_UPDATE ClassAttributeAssignment;classificationClass(code,catalogVersion(catalog(id),version))[unique=true];classificationAttribute(code,systemVersion(catalog(id),version))[unique=true];attributeType(code)[default=string]"]
        L += [f";{cls}:ccClassification:1.0;{a}:ccClassification:1.0;" for a in attrs]
        L += ["INSERT_UPDATE ProductFeature;product(code,catalogVersion(catalog(id),version))[unique=true];classificationAttributeAssignment(classificationClass(code,catalogVersion(catalog(id),version)),classificationAttribute(code,systemVersion(catalog(id),version)))[unique=true];qualifier[unique=true];value[translator=de.hybris.platform.catalog.jalo.classification.impex.ProductFeatureValueTranslator];language(isocode)"]
        for q in prods:
            for a, v in sorted(q["attributes"].items()):
                L.append(f";{q['code']}:{cv};{cls}:ccClassification:1.0:{a}:ccClassification:1.0;ccClassification/1.0/{cls}.{a.lower()};{esc(v)};en")
    L += ["", "INSERT_UPDATE B2BUnit;uid[unique=true];name;active[default=true]"]
    units = sorted({d['unit'] for d in m['dealers']})
    L += [f";{u};{esc(u)};" for u in units]
    L += ["INSERT_UPDATE B2BCustomer;uid[unique=true];name;email;groups(uid)[default=b2bgroup];defaultB2BUnit(uid);active[default=true]"]
    for d in m["dealers"]:
        L.append(f";{d['uid']};{esc(d['name'])};{d['uid']}@example.invalid;;{d['unit']};")
    cfg = lambda t, k, v: f";default;{t};{p};{k};{esc(v)};true;0"
    L += ["", "INSERT_UPDATE CCConfigEntry;configuration(code)[unique=true];entryType(code)[unique=true];packCode[unique=true];key[unique=true];value[lang=en];enabled;sortOrder"]
    am = m["attributeMapping"]
    L += [cfg("PACK", f"pack.{p}.categories", ",".join(c["code"] for c in m["categories"])),
          cfg("SEARCH_FIELD", f"pack.{p}.searchFields", ",".join(am["searchable"])),
          cfg("ATTRIBUTE_MAPPING", f"pack.{p}.attributes", ",".join(sorted(set(am["searchable"]) | set(am["comparison"])))),
          cfg("TERMINOLOGY", f"pack.{p}.terminology", ";".join(f"{k}={v}" for k, v in sorted(m["terminology"].items()))),
          cfg("PACK", f"pack.{p}.samplePrompts", "|".join(m["samplePrompts"])),
          cfg("PACK", f"pack.{p}.themeTokens", ";".join(f"{k}={v}" for k, v in sorted(m["theme"].items())))]
    for f in m["faq"]:
        L.append(cfg("FAQ", f["id"], f["question"] + "::" + f["answer"]))
    return "\n".join(L) + "\n"


def order_plan(m, prods):
    """Normalised order plan consumed by SampleOrderLoader. Dates are relative (daysAgo) so a 30-day rhythm is true on demo day."""
    price = {q["code"]: q["priceMinor"] for q in prods}
    plan = []
    for d in m["dealers"]:
        for o in d["orders"]:
            lines = [{"product": a, "quantity": b} for a, b in o["lines"]] if "lines" in o else [{"product": o["product"], "quantity": o["quantity"]}]
            days = o.get("daysAgo", [])
            days = days if isinstance(days, list) else [days]
            if "daysAgoLastMonth" in o:
                days = [{"lastMonthDay": o["daysAgoLastMonth"]}]
            for day in days:
                total = o.get("totalMinor") or sum(price[l["product"]] * l["quantity"] for l in lines)
                plan.append({"dealer": d["uid"], "lines": lines, "daysAgo": day, "status": o.get("status", "DELIVERED"),
                             "totalMinor": total, "tracking": o.get("tracking")})
    return plan


