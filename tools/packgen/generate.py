def main():
    schema = json.loads((HERE / "schema/pack.schema.json").read_text())
    manifests, errors = {}, []
    for f in sorted((HERE / "manifests").glob("*.json")):
        m = json.loads(f.read_text())
        errors += [f"{f.name}: {e}" for e in validate(m, schema)]
        manifests[m["pack"]] = m
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    caps = re.findall(r'"([A-Z]{2}-\d{2})"', re.search(r"ALL = List\.of\((.*?)\);", CAPS_JAVA.read_text(), re.S).group(1))
    assert len(caps) == 43, len(caps)
    (OUT / "essential").mkdir(parents=True, exist_ok=True)
    (OUT / "projectdata").mkdir(parents=True, exist_ok=True)
    (OUT / "orders").mkdir(parents=True, exist_ok=True)
    (OUT / "essential/essentialdata-cc-config.impex").write_text(essential(caps, manifests))
    allpacks = {"dealer": "dealer-all", "lines": []}
    for p, m in sorted(manifests.items()):
        prods = products_of(m)
        (OUT / f"projectdata/pack-{p}.impex").write_text(impex_pack(m))
        (OUT / f"orders/{p}.json").write_text(json.dumps(order_plan(m, prods), indent=2, sort_keys=True) + "\n")
        for q in m["products"][:2]:
            allpacks["lines"].append({"product": q["code"], "quantity": 10})
    # A4: one dealer who can see every pack (orders spread over all packs)
    allp = [{"dealer": "dealer-all", "lines": allpacks["lines"], "daysAgo": d, "status": "DELIVERED", "totalMinor": 100000, "tracking": None} for d in (90, 60, 30)]
    (OUT / "orders/all-packs.json").write_text(json.dumps(allp, indent=2, sort_keys=True) + "\n")
    (OUT / "projectdata/all-packs-dealer.impex").write_text(
        "# GENERATED. A4: one dealer with orders in every pack.\nINSERT_UPDATE B2BUnit;uid[unique=true];name;active[default=true]\n;demo-all-unit;demo-all-unit;\n"
        "INSERT_UPDATE B2BCustomer;uid[unique=true];name;email;groups(uid)[default=b2bgroup];defaultB2BUnit(uid);active[default=true]\n"
        ";dealer-all;Demo All-Packs Dealer;dealer-all@example.invalid;;demo-all-unit;\n")


main()
