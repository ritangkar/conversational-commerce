#!/usr/bin/env python3
"""Generates storefront/chat-feature/src/styles/_tokens.scss from tokens.json plus pack accents. `--check` fails if stale."""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "storefront/chat-feature/src/styles"


def render():
    tokens = json.loads((SRC / "tokens.json").read_text())["tokens"]
    out = ["// GENERATED by tools/ci/tokens.py from tokens.json. Do not edit.",
           "// Hex values must be confirmed against PwC's brand portal (docs/theming.md). No logo or font is bundled:",
           "// set --cc-logo-url and --cc-font-family in the host storefront.", ":root {"]
    out += [f"  {k}: {v};" for k, v in tokens.items()]
    out += ["  --cc-radius: 8px;", "  --cc-focus-ring: 3px solid var(--cc-color-ink);", "}", ""]
    for m in sorted((ROOT / "tools/packgen/manifests").glob("*.json")):
        d = json.loads(m.read_text())
        out += [f"[data-cc-pack='{d['pack']}'] {{"] + [f"  {k}: {v};" for k, v in d["theme"].items()] + ["}"]
    return "\n".join(out) + "\n"


text = render()
target = SRC / "_tokens.scss"
if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text() == text else (print("_tokens.scss is stale: run tools/ci/tokens.py") or 1))
target.write_text(text)
