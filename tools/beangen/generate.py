#!/usr/bin/env python3
"""Generates facade-beans.xml (*Data) and occ-beans.xml (*WsDTO) from tools/beangen/beans.json. Deterministic."""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = json.load(open(ROOT / "tools/beangen/beans.json"))["beans"]
SIMPLE = {"String", "Integer", "Boolean", "Long", "Double"}


def java_type(t, pkg, suffix):
    m = re.fullmatch(r"List<(.+)>", t)
    if m:
        return "java.util.List<" + java_type(m.group(1), pkg, suffix) + ">"
    m = re.fullmatch(r"Map<(.+),(.+)>", t)
    if m:
        return "java.util.Map<" + java_type(m.group(1), pkg, suffix) + "," + java_type(m.group(2), pkg, suffix) + ">"
    if t in SIMPLE:
        return "java.lang." + t
    return f"{pkg}.{t}{suffix}"


def render(pkg, suffix, comment):
    out = ['<?xml version="1.0" encoding="UTF-8"?>', f"<!-- {comment} -->",
           '<beans xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="beans.xsd">', ""]
    for name, props in SPEC.items():
        out.append(f'    <bean class="{pkg}.{name}{suffix}">')
        for p, t in props.items():
            out.append(f'        <property name="{p}" type="{java_type(t, pkg, suffix)}"/>')
        out.append("    </bean>")
        out.append("")
    out.append("</beans>")
    return "\n".join(out) + "\n"


def main():
    targets = {
        ROOT / "backend/ccfacades/resources/ccfacades-beans.xml": ("com.conversational.commerce.facades.data.chat", "Data",
                                                                    "GENERATED by tools/beangen/generate.py. Facade DTOs (*Data), convention: facade-beans.xml."),
        ROOT / "backend/ccocc/resources/ccocc-beans.xml": ("com.conversational.commerce.occ.chat", "WsDTO",
                                                           "GENERATED by tools/beangen/generate.py. OCC DTOs (*WsDTO), convention: occ-beans.xml."),
    }
    check = "--check" in sys.argv
    bad = False
    for path, (pkg, suffix, comment) in targets.items():
        text = render(pkg, suffix, comment)
        if check:
            bad |= not path.exists() or path.read_text() != text
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check and bad:
        print("bean XML is out of date: run tools/beangen/generate.py")
        sys.exit(1)


main()
